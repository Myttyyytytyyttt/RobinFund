import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "../../..");
const contractsOutput = resolve(repositoryRoot, "packages/contracts/out");
const contractsSource = resolve(repositoryRoot, "packages/contracts/src");
const contractsFoundryConfig = resolve(repositoryRoot, "packages/contracts/foundry.toml");
const generatedFile = resolve(scriptDirectory, "../src/generated/vault-artifacts.ts");
const checkOnly = process.argv.includes("--check");
const checkSourceOnly = process.argv.includes("--check-source");

const sources = [
  {
    exportName: "agentVaultControllerArtifact",
    relativePath: "AgentVaultController.sol/AgentVaultController.json",
  },
  {
    exportName: "fundArtifact",
    relativePath: "Fund.sol/Fund.json",
  },
];

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => [key, stable(entry)]),
  );
}

function validateLinkReferences(linkReferences, relativePath) {
  let count = 0;
  for (const libraries of Object.values(linkReferences)) {
    for (const [library, positions] of Object.entries(libraries)) {
      if (library !== "NAVLib") {
        throw new Error(`${relativePath} contains unsupported library ${library}`);
      }
      for (const position of positions) {
        if (
          !Number.isInteger(position.start)
          || position.start < 0
          || position.length !== 20
        ) {
          throw new Error(`${relativePath} contains an invalid NAVLib link reference`);
        }
        count += 1;
      }
    }
  }
  if (count === 0) throw new Error(`${relativePath} does not contain a NAVLib link reference`);
}

async function readArtifact(relativePath) {
  const path = resolve(contractsOutput, relativePath);
  let source;
  try {
    source = JSON.parse(await readFile(path, "utf8"));
  } catch (error) {
    throw new Error(
      `Cannot read ${path}. Run "forge build --root packages/contracts" first.`,
      { cause: error },
    );
  }
  if (!Array.isArray(source.abi)) throw new Error(`${relativePath} is missing its ABI`);
  if (
    typeof source.bytecode?.object !== "string"
    || !source.bytecode.object.startsWith("0x")
  ) {
    throw new Error(`${relativePath} is missing creation bytecode`);
  }
  const linkReferences = source.bytecode.linkReferences ?? {};
  validateLinkReferences(linkReferences, relativePath);
  return stable({
    abi: source.abi,
    bytecode: {
      object: source.bytecode.object,
      linkReferences,
    },
  });
}

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) paths.push(...await sourceFiles(path));
    else if (entry.isFile() && entry.name.endsWith(".sol")) paths.push(path);
  }
  return paths;
}

async function contractSourceHash() {
  const paths = [...await sourceFiles(contractsSource), contractsFoundryConfig]
    .sort((left, right) => left.localeCompare(right));
  const hash = createHash("sha256");
  for (const path of paths) {
    const relative = path.slice(repositoryRoot.length + 1).replaceAll("\\", "/");
    hash.update(relative);
    hash.update("\0");
    const source = await readFile(path, "utf8");
    hash.update(source.replace(/\r\n?/g, "\n"));
    hash.update("\0");
  }
  return hash.digest("hex");
}

async function generateArtifacts(sourceTreeHash) {
  const artifacts = [];
  for (const source of sources) {
    artifacts.push({
      ...source,
      artifact: await readArtifact(source.relativePath),
    });
  }

  const canonicalPayload = JSON.stringify(
    Object.fromEntries(artifacts.map(({ exportName, artifact }) => [exportName, artifact])),
  );
  const sourceHash = createHash("sha256").update(canonicalPayload).digest("hex");
  const exports = artifacts
    .map(({ exportName, artifact }) => (
      `export const ${exportName}: GeneratedVaultArtifact = ${JSON.stringify(artifact, null, 2)};`
    ))
    .join("\n\n");
  const output = `/* eslint-disable */
// Generated by scripts/generate-vault-artifacts.mjs from Foundry output.
// Do not edit by hand. Regenerate after changing either deployment contract.
import type { Abi, Hex } from "viem";

export interface GeneratedVaultArtifact {
  abi: Abi;
  bytecode: {
    object: Hex;
    linkReferences: Record<string, Record<string, Array<{ start: number; length: number }>>>;
  };
}

export const vaultArtifactsSourceSha256 = "${sourceHash}";
export const vaultArtifactsContractSourceSha256 = "${sourceTreeHash}";

${exports}
`;

  if (checkOnly) {
    let existing = "";
    try {
      existing = await readFile(generatedFile, "utf8");
    } catch {
      // The comparison below reports the actionable error.
    }
    if (existing !== output) {
      throw new Error(
        `${generatedFile} is stale. Run "pnpm --dir apps/agent-gateway generate:vault-artifacts".`,
      );
    }
  } else {
    await mkdir(dirname(generatedFile), { recursive: true });
    await writeFile(generatedFile, output);
  }
}

const sourceTreeHash = await contractSourceHash();
if (checkSourceOnly) {
  const existing = await readFile(generatedFile, "utf8");
  if (!existing.includes(`export const vaultArtifactsContractSourceSha256 = "${sourceTreeHash}";`)) {
    throw new Error(
      `${generatedFile} was generated from stale contract sources. Run "forge build --root packages/contracts" and regenerate the vault artifacts.`,
    );
  }
} else {
  await generateArtifacts(sourceTreeHash);
}
